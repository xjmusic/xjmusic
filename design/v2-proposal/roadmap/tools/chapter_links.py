#!/usr/bin/env python3
"""Append (or refresh) an "Implementation issues" appendix in each proposal chapter.

  python3 -I tools/chapter_links.py

For every chapter a task cites in its `proposal_refs` (master.json), the script writes
a table from the cited section to the issues that implement it, between the markers
`<!-- roadmap-issues:begin -->` and `<!-- roadmap-issues:end -->` at the end of the
chapter file. Everything above the markers is left untouched, so the appendix can be
regenerated after every tracker change.
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROPOSAL = os.path.dirname(ROOT)
REPO_URL = "https://github.com/xjmusic/xjmusic"
BEGIN, END = "<!-- roadmap-issues:begin -->", "<!-- roadmap-issues:end -->"
DOC_ALIASES = {"10-risks": "10-risks-and-open-questions.md", "11-resolutions": "11-resolutions.md"}


def split_ref(ref):
    """'04-engine.md §6' -> ('04-engine.md', '§6'); '10-risks R3' -> ('10-risks-and-open-questions.md', 'R3')."""
    ref = ref.strip()
    parts = ref.split(None, 1)
    doc = parts[0]
    section = parts[1].strip() if len(parts) > 1 else "(whole chapter)"
    doc = DOC_ALIASES.get(doc, doc)
    if not doc.endswith(".md"):
        doc += ".md"
    return doc, section


def main():
    m = json.load(open(os.path.join(ROOT, "master.json")))
    imap = json.load(open(os.path.join(ROOT, "issue-map.json")))
    by_doc = collections.defaultdict(lambda: collections.defaultdict(list))
    for t in m["tasks"]:
        for ref in t.get("proposal_refs", []):
            doc, section = split_ref(ref)
            by_doc[doc][section].append(t)
    written = 0
    for doc, sections in sorted(by_doc.items()):
        path = os.path.join(PROPOSAL, doc)
        if not os.path.exists(path):
            print("no such chapter, skipped:", doc)
            continue
        rows = []
        for section in sorted(sections, key=lambda s: (re.sub(r"\d+", lambda mm: mm.group(0).zfill(3), s))):
            seen = []
            for t in sections[section]:
                if t["key"] not in seen:
                    seen.append(t["key"])
            links = ", ".join(f"[#{imap[k]['number']}]({REPO_URL}/issues/{imap[k]['number']})" if k in imap else f"`{k}`" for k in seen)
            rows.append(f"| {section} | {links} |")
        block = "\n".join([BEGIN, "", "## Implementation issues", "", "*Generated by `roadmap/tools/chapter_links.py` from the tasks that cite this chapter. The roadmap is [12-work-breakdown.md](12-work-breakdown.md); the issues are the source of truth for status.*", "", "| Section cited | Issues |", "|---|---|", *rows, "", END, ""])
        text = open(path).read()
        if BEGIN in text and END in text:
            head = text[: text.index(BEGIN)].rstrip("\n") + "\n\n"
        else:
            head = text.rstrip("\n") + "\n\n"
        with open(path, "w") as f:
            f.write(head + block)
        written += 1
        print(f"{doc}: {len(rows)} sections")
    print("chapters updated:", written)


if __name__ == "__main__":
    main()
