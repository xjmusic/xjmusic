#!/usr/bin/env python3
"""Append (or refresh) an "Implementation issues" appendix in each proposal chapter.

  python3 -I tools/chapter_links.py

For every chapter a task cites in its `proposal_refs` (master.json), the script writes
a table from the cited section to the issues that implement it, between the markers
`<!-- roadmap-issues:begin -->` and `<!-- roadmap-issues:end -->` near the end of the
chapter file. Text above the markers and anything after the end marker (footnotes,
for example) is left untouched, so the appendix can be regenerated after every
tracker change. A chapter that is no longer cited loses its appendix.
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROPOSAL = os.path.dirname(ROOT)
REPO_URL = "https://github.com/xjmusic/xjmusic"
BEGIN, END = "<!-- roadmap-issues:begin -->", "<!-- roadmap-issues:end -->"
DOC_ALIASES = {"10-risks": "10-risks-and-open-questions.md", "11-resolutions": "11-resolutions.md"}
SECTION_TOKEN = re.compile(r"^(§[\d.]+|R\d+|Q\d+)$")


def split_ref(ref):
    """'04-engine.md §6' -> [('04-engine.md', '§6')]; '10-risks R3 R12' -> [(.., 'R3'), (.., 'R12')]."""
    ref = ref.strip()
    parts = ref.split(None, 1)
    doc = DOC_ALIASES.get(parts[0], parts[0])
    if not doc.endswith(".md"):
        doc += ".md"
    if len(parts) == 1:
        return [(doc, "(whole chapter)")]
    rest = parts[1].strip()
    tokens = [t for t in re.split(r"[\s,]+", rest) if t and t not in ("and", "&")]
    if len(tokens) > 1 and all(SECTION_TOKEN.match(t) for t in tokens):
        return [(doc, t) for t in tokens]
    return [(doc, rest)]


def section_key(s):
    return re.sub(r"\d+", lambda mm: mm.group(0).zfill(3), s)


def strip_block(text, path):
    """Return (head, tail): the text before BEGIN and after END, or (text, '') when there is no block."""
    has_begin, has_end = BEGIN in text, END in text
    if has_begin != has_end:
        raise SystemExit(f"{path}: only one of the roadmap-issues markers is present; restore or remove the other before regenerating")
    if not has_begin:
        return text, ""
    head = text[: text.index(BEGIN)]
    tail = text[text.index(END) + len(END):]
    return head, tail


def main():
    m = json.load(open(os.path.join(ROOT, "master.json")))
    imap = json.load(open(os.path.join(ROOT, "issue-map.json")))
    by_doc = collections.defaultdict(lambda: collections.defaultdict(list))
    for t in m["tasks"]:
        for ref in t.get("proposal_refs", []):
            for doc, section in split_ref(ref):
                if t["key"] not in by_doc[doc][section]:
                    by_doc[doc][section].append(t["key"])
    # every file that currently carries an appendix, so one that lost its citations is cleaned up
    marked = set()
    for dirpath, _, files in os.walk(PROPOSAL):
        for f in files:
            if f.endswith(".md"):
                p = os.path.join(dirpath, f)
                with open(p) as fh:
                    if BEGIN in fh.read():
                        marked.add(os.path.relpath(p, PROPOSAL))
    written = 0
    for doc in sorted(set(by_doc) | marked):
        path = os.path.join(PROPOSAL, doc)
        if not os.path.exists(path):
            print("no such chapter, skipped:", doc)
            continue
        with open(path) as fh:
            text = fh.read()
        head, tail = strip_block(text, doc)
        head = head.rstrip("\n") + "\n"
        tail = tail.lstrip("\n")
        sections = by_doc.get(doc, {})
        if not sections:
            new = head + ("\n" + tail if tail else "")
            print(f"{doc}: no longer cited, appendix removed")
        else:
            wb = os.path.relpath(os.path.join(PROPOSAL, "12-work-breakdown.md"), os.path.dirname(path))
            rows = []
            for section in sorted(sections, key=section_key):
                links = ", ".join(f"[#{imap[k]['number']}]({REPO_URL}/issues/{imap[k]['number']})" if k in imap else f"`{k}`" for k in sections[section])
                rows.append(f"| {section} | {links} |")
            block = "\n".join([BEGIN, "", "## Implementation issues", "", f"*Generated by `roadmap/tools/chapter_links.py` from the tasks that cite this chapter. The roadmap is [12-work-breakdown.md]({wb}); the issues are the source of truth for status.*", "", "| Section cited | Issues |", "|---|---|", *rows, "", END, ""])
            new = head + "\n" + block + ("\n" + tail if tail else "")
            print(f"{doc}: {len(rows)} sections")
        if new != text:
            with open(path, "w") as fh:
                fh.write(new)
            written += 1
    print("chapters updated:", written)


if __name__ == "__main__":
    main()
